# The hardware model exposes these two same-linked data islands on the data
# bus while leaving the flat 33:* code bytes visible to instruction fetches.
# Both are sources in the vendor's second initializer chain, so the expected
# image must apply the same evidenced Harvard aliases before comparing RAM.
INITIALIZER_DATA_SOURCE_ALIASES = (
    (0x331428, 0x501428, 0x30),
    (0x33707C, 0x50707C, 0x04),
)

# The resident launch wrapper passes 31:F5E2 as a data pointer, although the
# flat bytes at that logical address are executable code.  The linked +0x1d
# source terminates immediately before the balanced function at 4E:F670.
LAUNCH_RESOURCE_DATA_ALIAS = (0x31F5E2, 0x4EF5E2, 0x8E)

# Exact 30:07BE indexes 24 four-byte position pointers at data address
# 33:1368.  The flat bank is code; source 50:1368 contains the table and the
# next balanced function begins immediately at 50:13C8.
MENU_POSITION_DATA_ALIAS = (0x331368, 0x501368, 0x60)

# Source 41:162C follows the eight-bit parent field in this 26-word table.
# Entry six points to entry 25, so truncating the alias to sixteen words falls
# through into adjacent flat code and creates a 7/6/F cycle.  The word after
# entry 25 begins a different data island and bounds the alias at 0x34 bytes.
MODAL_STATE_TABLE_DATA_ALIAS = (0x3307E4, 0x5007E4, 0x34)

# Source 3B:64DA consumes the complete runtime-data string island at
# 2F:F37E..F49B.  This includes the two directory suffixes at F3DC/F418 and
# the resource strings at F46A..F49B.  The flat target is code; the linked
# +0x1d bank begins after the balanced RETS at 4C:F37C and ends immediately
# before the next balanced function at source 4C:F49C.
PIM_RESOURCE_DATA_ALIAS = (0x2FF37E, 0x4CF37E, 0x11E)

# Exact 2A:A746 file-open passes 28:E368 as a data pointer.  Code fetches at
# that address remain executable overlay instructions; source 45:E368 is the
# bounded external-lane string "0:\\USERINFO.SYS\0".
USERINFO_PATH_DATA_ALIAS = (0x28E368, 0x45E368, 0x10)

# Source 46:F732 passes 31:940E to fopen.  The logical destination is code on
# the instruction bus and a separate sixteen-byte RAM path on the data bus;
# the guest installer copies source 4E:940E there.
USERINFO_LITERAL_DATA_ALIAS = (0x31940E, 0x4E940E, 0x10)

