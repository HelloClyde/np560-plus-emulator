#!/usr/bin/env python3
"""Read-only, representation-bounded MPEG table search in original NP560 files.

Reference data is parsed from the two saved FFmpeg source files; no decoder is
executed or installed. Matches are candidates, not proof of a ROM algorithm.
No match only excludes the enumerated exact, contiguous representations.
"""
from __future__ import annotations

import argparse
import hashlib
import itertools
import json
import math
from pathlib import Path
import re
import struct

from np560_upd import parse_update

REFERENCE_HASHES = {
    "mpegaudiodec_common.c": "e6a415c3c47670217b49a97ca71adbbed4d98433d852e276539293465cb67151",
    "mpegaudiodsp_data.c": "b4c590d2bc880017cdda8c857f4340274449f4749c992f1d1cef785f9196d7a8",
}


def array(source, name):
    source = re.sub(r"/\*.*?\*/", "", source, flags=re.S)
    match = re.search(r"\b" + re.escape(name) + r"(?:\[[^]]*\])+\s*=\s*\{(.*?)\};", source, re.S)
    if not match:
        raise ValueError(f"missing reference table {name}")
    return [int(s, 0) if "x" in s.lower() else int(s)
            for s in re.findall(r"-?0x[0-9a-fA-F]+|-?\d+", match[1])]


def fingerprints(reference):
    sources = {}
    for name, expected in REFERENCE_HASHES.items():
        raw = (reference / name).read_bytes()
        if hashlib.sha256(raw).hexdigest() != expected:
            raise ValueError(f"reference hash differs: {name}")
        sources[name] = raw.decode("utf-8")
    patterns = {}

    def emit(label, values):
        for fmt in ("B", "H", "I"):
            if not values or min(values) < 0 or max(values) >= 1 << (struct.calcsize(fmt) * 8):
                continue
            for endian in ("<", ">"):
                data = struct.pack(endian + str(len(values)) + fmt, *values)
                if len(data) < 13:
                    continue
                patterns.setdefault(data, []).append(f"{label}:{endian}{fmt}")
                # Pair-swapped byte strings cover the DMCU file/data lane
                # representation; retain odd trailing bytes as a boundary.
                if len(data) % 2 == 0:
                    swapped = bytearray(data)
                    swapped[0::2], swapped[1::2] = data[1::2], data[0::2]
                    patterns.setdefault(bytes(swapped), []).append(f"{label}:{endian}{fmt}:swap16")

    # Independently fixed MPEG-1 Layer III bitrate values, already located
    # in the original header parser table. This checks source representation
    # and update byte lanes, and MUST NOT count as finding a decoder.
    emit("positive-control/parser-bitrates", [0, 32, 40, 48, 56, 64, 80, 96,
                                             112, 128, 160, 192, 224, 256, 320, 0])
    common = sources["mpegaudiodec_common.c"]
    for name, count, row_size in (("ff_slen_table", 32, 16),
                                 ("ff_lsf_nsf_table", 72, 12),
                                 ("ff_band_size_long", 198, 22),
                                 ("ff_band_size_short", 117, 13)):
        values = array(common, name)
        assert len(values) == count, (name, len(values))
        emit(name, values)
        for i in range(0, count, row_size):
            row = values[i:i+row_size]
            label = f"{name}[{i//row_size}]"
            emit(label, row)
            if name.startswith("ff_band_size"):
                # Widths, cumulative boundaries, and the half-width pair
                # coordinates explicitly generated by FFmpeg's initializer.
                for scale, scaled in (("full", row), ("half", [v//2 for v in row])):
                    ends = list(itertools.accumulate(scaled))
                    emit(f"{label}/{scale}/widths", scaled)
                    emit(f"{label}/{scale}/bounds", [0, *ends])
                    emit(f"{label}/{scale}/starts", [0, *ends[:-1]])

    sizes = [x+1 for x in array(common, "mpa_huff_sizes_minus_one")]
    lens, symbols = array(common, "mpa_hufflens"), array(common, "mpa_huffsymbols")
    assert sum(sizes) == len(lens) == len(symbols)
    cursor = 0
    for table_id, count in zip((1, 2, 3, 5, 6, 7, 8, 9, 10, 11, 12, 13, 15, 16, 24), sizes, strict=True):
        ls, sy = lens[cursor:cursor+count], symbols[cursor:cursor+count]
        cursor += count
        if count < 16:
            continue
        emit(f"huff{table_id}/ffmpeg-lengths", ls)
        emit(f"huff{table_id}/ffmpeg-symbols", sy)
        emit(f"huff{table_id}/xy-sorted-lengths", [n for _, n in sorted(zip(sy, ls))])

    window = array(sources["mpegaudiodsp_data.c"], "ff_mpa_enwindow")
    assert len(window) == 257 and window[-1] == 75038
    # Search nontrivial consecutive fragments as well as the whole table.
    # These do not cover arbitrary transpositions or platform-specific DSP
    # factorizations. Scaling/rounding below is a search hypothesis only.
    for offset, values in [(0, window), *[(i, window[i:i+32]) for i in range(32, 225, 32)]]:
        for scale in (1, 0.5, 0.25, 0.125, 4096):
            for rounding, quantize in (("floor", math.floor), ("trunc", math.trunc), ("nearest", round)):
                q = [quantize(v*scale) for v in values]
                for sign, converted in (("signed", q), ("negated", [-v for v in q]), ("abs", list(map(abs, q)))):
                    for fmt, low, high in (("h", -32768, 32767), ("i", -2147483648, 2147483647)):
                        if min(converted) < low or max(converted) > high:
                            continue
                        for endian in ("<", ">"):
                            data = struct.pack(endian+str(len(converted))+fmt, *converted)
                            patterns.setdefault(data, []).append(
                                f"window[{offset}:{offset+len(values)}]/{scale}/{rounding}/{sign}/{endian}{fmt}")
    return patterns


def find_all(blob, needle):
    start = 0
    while (index := blob.find(needle, start)) >= 0:
        yield index
        start = index + 1


def self_check(patterns):
    # Known inserted numeric data, overlap handling, swap16 and negative
    # controls guard the scanner itself, not any emulator capability.
    sample = bytes.fromhex("0400060008000a000c000e001000")
    swapped = bytes.fromhex("000400060008000a000c000e0010")
    assert list(find_all(b"aaa", b"aa")) == [0, 1]
    assert list(find_all(b"x"*7 + sample + b"x"*11, sample)) == [7]
    assert list(find_all(swapped, sample)) == []
    chosen = next(p for p in patterns if len(p) > 30 and len(set(p)) > 9)
    assert list(find_all(bytes(19)+chosen+bytes(5), chosen)) == [19]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("inputs", nargs="+", type=Path)
    parser.add_argument("--reference", type=Path, default=Path(__file__).resolve().parents[1] / "doc/sources/ffmpeg-mpeg-tables-20260907")
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    if args.output.exists():
        parser.error("output already exists; choose a fresh report")
    patterns = fingerprints(args.reference)
    self_check(patterns)
    report = {"reference_sha256": REFERENCE_HASHES, "pattern_count": len(patterns),
              "coverage": "exact contiguous numeric tables/rows/fragments in enumerated encodings only",
              "decoder_presence_proven": False, "decoder_absence_proven": False,
              "self_check_passed": True, "inputs": []}
    for path in args.inputs:
        blob = path.read_bytes()
        blocks = parse_update(path).blocks if path.suffix.lower() == ".upd" else ()
        item = {"path": str(path), "size": len(blob), "sha256": hashlib.sha256(blob).hexdigest(),
                "blocks": [{"slot": b.slot, "offset": b.offset, "size": b.size, "kind": b.kind} for b in blocks], "hits": []}
        for pattern, labels in patterns.items():
            for offset in find_all(blob, pattern):
                hit = {"offset": offset, "offset_hex": f"0x{offset:x}", "length": len(pattern), "labels": labels}
                for b in blocks:
                    if b.offset <= offset and offset+len(pattern) <= b.offset+b.size:
                        hit.update(slot=b.slot, block_offset=offset-b.offset, block_kind=b.kind)
                if path.suffix.lower() == ".prg":
                    hit["vma03"] = f"{(offset+0x30000)>>16:02X}:{(offset+0x30000)&65535:04X}"
                item["hits"].append(hit)
        report["inputs"].append(item)
        item["positive_control_matches"] = sum(all(label.startswith("positive-control/") for label in hit["labels"])
                                               for hit in item["hits"])
        item["decoder_table_candidates"] = len(item["hits"]) - item["positive_control_matches"]
        print(f"{path.name}: {item['decoder_table_candidates']} candidates, "
              f"{item['positive_control_matches']} parser controls; {len(patterns)} representations", flush=True)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("x", encoding="utf-8") as stream:
        json.dump(report, stream, indent=2)
        stream.write("\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
